<#
.Synopsis
   Get OneDrive Status
.DESCRIPTION
   Get OneDrive Status using the new available API in Windows 11 and some new Windows 10 Versions
.EXAMPLE
   Get-ODStatus
.EXAMPLE
   Get-ODStatus -ExePath d:\tools\

#>
    [OutputType([pscustomobject])]
    Param
    (
        
        [Parameter(Mandatory=$false,
                   ValueFromPipelineByPropertyName=$true,
                   Position=0)]
        [string]$ExePath = "$PSScriptRoot"
    )
    if ([string]::IsNullOrEmpty($ExePath)) {
        # it should only be null if the user passed in an empty string, or it is running outside of the script (select + Run for example),
        #  so we will use the current directory
        $ExePath = "."
    }
    $exeName = "$ExePath\ODSyncUtil.exe"

    if(-not (Test-Path $exeName)) {
       Write-Error "$exeName not found. Exiting"
       return $null
    }

    & $exeName | Tee-Object -Variable output | Out-Null
    $result = ConvertFrom-Json -InputObject $output
    return $result


